class SubstringDemo {
    public static void main(String[] args) {
        String str = "Programming";
        
        System.out.println("Original = " + str);
        System.out.println("From index 3 = " + str.substring(3));
        System.out.println("From index 4 = " + str.substring(4));
        System.out.println("From index 5 = " + str.substring(5));
        System.out.println("substring() extracts part of string");
    }
}
