class CharAtDemo {
    public static void main(String[] args) {
        String str = "Java";
        
        System.out.println("String = " + str);
        System.out.println("Character at 0 = " + str.charAt(0));
        System.out.println("Character at 1 = " + str.charAt(1));
        System.out.println("Character at 2 = " + str.charAt(2));
        System.out.println("Character at 3 = " + str.charAt(3));
        System.out.println("Using charAt() method");
    }
}
