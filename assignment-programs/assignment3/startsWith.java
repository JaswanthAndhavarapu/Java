class StartsDemo {
    public static void main(String[] args) {
        String str = "Java Programming";
        
        System.out.println("String = " + str);
        System.out.println("Starts with Java = " + str.startsWith("Java"));
        System.out.println("Starts with Pro = " + str.startsWith("Pro"));
        System.out.println("Starts with Python = " + str.startsWith("Python"));
        System.out.println("startsWith() checks beginning");
    }
}
